import { copyFileSync, existsSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { _electron as electron, expect, test } from '@playwright/test';
import type { SerpentLibraryApi } from '../../src/shared/library-api';
import { resolveElectronExecutablePath, openAppSettingsDialog } from './electron-test-helpers';
import { removePathWithSyncRetry } from '../../src/worker/windows-fs-retry';
test.setTimeout(120_000);
test('tag appearance, reverse image drop and persistent interface scale', async () => {
  const root = mkdtempSync(path.join(tmpdir(), 'serpent-tag-style-'));
  const appDirectory = process.env.KEEL_E2E_APP_DIRECTORY ?? process.cwd();
  const app = await electron.launch({ executablePath: resolveElectronExecutablePath(),
    args: process.env.KEEL_E2E_ELECTRON_EXECUTABLE ? [] : [appDirectory], cwd: appDirectory,
    env: { ...process.env, KEEL_E2E: '1', KEEL_E2E_USER_DATA_PATH: path.join(root, 'profile'), KEEL_E2E_CREATE_PARENT_PATH: root } });
  try {
    await app.evaluate(({ dialog }, selected) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] }); }, root);
    const window = await app.firstWindow();
    await window.getByRole('button', { name: '创建资源库', exact: true }).click();
    await window.getByRole('textbox', { name: '名称', exact: true }).fill('外观测试');
    await window.getByRole('button', { name: '创建', exact: true }).click();
    const panel = window.getByRole('region', { name: '标签', exact: true });
    await panel.getByRole('button', { name: '新建标签', exact: true }).click();
    await panel.getByRole('textbox', { name: '标签名称', exact: true }).fill('角色');
    await panel.getByRole('button', { name: '保存', exact: true }).click();
    const tag = panel.getByRole('treeitem', { name: '角色', exact: true });
    await expect(tag).toBeVisible();
    const libraryId = await window.evaluate(async () => {
      const api = (globalThis as typeof globalThis & { serpent: { library: SerpentLibraryApi } }).serpent.library;
      const result = await api.listOpen(); if (!result.ok) throw new Error('No library'); return result.value[0]!.libraryId;
    });
    const tags = () => window.evaluate(async id => { const api = (globalThis as typeof globalThis & { serpent: { library: SerpentLibraryApi } }).serpent.library; const result = await api.listTags({ libraryId: id }); if (!result.ok) throw new Error('No tags'); return result.value; }, libraryId);
    expect((await tags())[0]?.appearance?.colorId).toBeTruthy();
    expect((await tags())[0]?.appearance?.glyphValue).toBeTruthy();
    await tag.click({ button: 'right' });
    await window.getByRole('menuitem', { name: '颜色和图标', exact: true }).click();
    const picker = panel.getByRole('group', { name: '颜色和图标', exact: true });
    await picker.getByRole('button', { name: '蓝', exact: true }).click();
    await picker.getByRole('button', { name: '🎨', exact: true }).click();
    await picker.getByRole('button', { name: '保存', exact: true }).click();
    await expect.poll(async () => (await tags())[0]?.appearance).toEqual({ colorId: 'blue', glyphKind: 'emoji', glyphValue: '🎨' });
    writeFileSync(path.join(root, '外观测试', 'image.png'), Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j5ZkAAAAASUVORK5CYII=', 'base64'));
    copyFileSync(path.join(root, '外观测试', 'image.png'), path.join(root, '外观测试', 'second.png'));
    const card = window.locator('.asset-card').filter({ hasText: 'image.png' }).first();
    await expect(card).toBeVisible({ timeout: 20000 });
    const second = window.locator('.asset-card').filter({ hasText: 'second.png' }).first();
    await expect(second).toBeVisible();
    await card.click(); await second.click({ modifiers: ['Control'] });
    const transfer = await window.evaluateHandle(id => { const data = new DataTransfer(); data.setData('application/x-serpent-tag', id); return data; }, (await tags())[0]!.tagId);
    await tag.dispatchEvent('dragstart', { dataTransfer: transfer });
    await card.dispatchEvent('dragover', { dataTransfer: transfer });
    await expect(card).toHaveAttribute('data-tag-drop-target', 'true');
    await card.dispatchEvent('drop', { dataTransfer: transfer });
    await expect.poll(async () => (await tags())[0]?.assetCount).toBe(2);
    await tag.dispatchEvent('dragend', { dataTransfer: transfer });
    await tag.click(); await expect(card).toBeVisible();
    const filter = window.locator('.dimension-filter-bar');
    await expect(filter.getByRole('button', { name: '颜色', exact: true })).toHaveCount(0);
    const more = filter.getByRole('button', { name: '更多', exact: true });
    await expect(more.locator('svg')).toHaveAttribute('width', '18');
    expect((await more.boundingBox())!.height).toBeGreaterThanOrEqual(34);
    await more.click();
    const popover = window.locator('[data-dimension-filter-popover][data-dimension="more"]');
    await expect(popover.locator('summary').filter({ hasText: '颜色' })).toBeVisible();
    await expect(popover.locator('summary').filter({ hasText: '形状' })).toBeVisible();
    await window.screenshot({ path: test.info().outputPath('tag-customization-filters.png') });
    await window.keyboard.press('Escape');
    const settings = await openAppSettingsDialog(app, window);
    await settings.getByRole('tab', { name: '外观', exact: true }).click();
    const scale = settings.getByRole('slider', { name: '界面缩放', exact: true });
    await expect(scale).toBeVisible();
    await scale.focus();
    for (let i = 0; i < 5; i++) await window.keyboard.press('ArrowRight');
    await expect(scale).toHaveValue('125');
    await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.webContents.getZoomFactor())).toBe(1.25);
    await scale.scrollIntoViewIfNeeded();
    const capture = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0]!.webContents.capturePage()).toPNG().toString('base64'));
    writeFileSync(test.info().outputPath('interface-scale-125.png'), Buffer.from(capture, 'base64'));
    await window.reload();
    await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.webContents.getZoomFactor())).toBe(1.25);
    await expect(panel.getByRole('treeitem', { name: '角色', exact: true })).toBeVisible();
    expect((await tags())[0]?.appearance).toEqual({ colorId: 'blue', glyphKind: 'emoji', glyphValue: '🎨' });
    expect(existsSync(path.join(root, '外观测试', 'image.png'))).toBe(true);
  } finally { await app.close(); removePathWithSyncRetry(root); }
});
